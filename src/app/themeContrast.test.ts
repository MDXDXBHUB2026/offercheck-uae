import { readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { isColour, themeTokens } from "./themeCss";
import { HERO_TEXT, PAIRS, heroRatio, ratioOf } from "./themePairs";

// Phase 4b: WCAG AA for both themes, read from the tokens in src/app/globals.css. The table of every
// pair and its ratio is docs/theme-contrast.md; this test fails if the table is out of date
// (run with UPDATE_THEME_DOC=1 to rewrite it).

const MIN = { text: 4.5, graphic: 3 } as const;

describe.each(["dark", "light"] as const)("%s theme: contrast", (theme) => {
  it.each(PAIRS.map((p) => [`${p.kind} ${p.fg} on ${p.bg} (${p.use}) is at least ${MIN[p.kind]}:1`, p] as const))("%s", (_name, p) => {
    expect(ratioOf(theme, p.fg, p.bg)).toBeGreaterThanOrEqual(MIN[p.kind]);
  });

  it.each(HERO_TEXT)("hero text %s on the glass keeps 4.5:1 over the worst video pixel", (fg) => {
    expect(heroRatio(theme, fg)).toBeGreaterThanOrEqual(4.5);
  });
});

describe("the copies of the light tokens", () => {
  const light = themeTokens("light");
  it("the system theme (inside prefers-color-scheme: light) has the same tokens as light", () => {
    expect(themeTokens("system")).toEqual(light);
  });
  it("print uses the same tokens as light, whatever the theme on screen", () => {
    expect(themeTokens("print")).toEqual(light);
  });
  it("light sets every colour token of the dark block, and nothing that dark does not have", () => {
    const dark = themeTokens("dark");
    for (const name of Object.keys(dark).filter((k) => isColour(dark[k]))) expect(light[name], name).toBeDefined();
    for (const name of Object.keys(light)) expect(dark[name], name).toBeDefined();
    expect(Object.keys(light).filter((k) => !isColour(light[k]))).toEqual(["--shadow"]);
  });
});

describe("the table in docs/theme-contrast.md", () => {
  const cell = (r: number, need: number) => `${r.toFixed(2)} ${r >= need ? "pass" : "FAIL"}`;
  const rows = PAIRS.map(
    (p) =>
      `| ${p.kind} | \`--${p.fg}\` on \`--${p.bg}\` | ${p.use} | ${MIN[p.kind]}:1 | ${cell(ratioOf("dark", p.fg, p.bg), MIN[p.kind])} | ${cell(ratioOf("light", p.fg, p.bg), MIN[p.kind])} |`,
  );
  const hero = HERO_TEXT.map(
    (fg) => `| text | \`--${fg}\` on \`--hero-glass\` over the worst video pixel | hero text | 4.5:1 | ${cell(heroRatio("dark", fg), 4.5)} | ${cell(heroRatio("light", fg), 4.5)} |`,
  );
  const table = [
    "# Theme contrast (Phase 4b)",
    "",
    "Generated by `src/app/themeContrast.test.ts` from the tokens in `src/app/globals.css`; do not edit by hand (`UPDATE_THEME_DOC=1 npx vitest run src/app/themeContrast.test.ts` rewrites it). WCAG 2.x contrast ratio. Text needs 4.5:1; graphics (input borders, focus rings, icons, scrollbar thumb) need 3:1. Dark is the default theme and is unchanged from before Phase 4b; its pairs are checked with the same list.",
    "",
    "| Kind | Pair | Used for | Needs | Dark | Light |",
    "|---|---|---|---|---|---|",
    ...rows,
    ...hero,
    "",
  ].join("\n");

  it("is up to date", () => {
    if (process.env.UPDATE_THEME_DOC) writeFileSync("docs/theme-contrast.md", table);
    expect(readFileSync("docs/theme-contrast.md", "utf8").replaceAll("\r\n", "\n")).toBe(table);
  });
});
