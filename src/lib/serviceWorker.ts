// The installable web app's service worker (production hardening Phase 4a, 2026-11-16), served at
// /sw.js by src/app/sw.js/route.ts. It is plain JavaScript text so the browser runs it as it is;
// src/lib/serviceWorker.test.ts runs this same text against stand-in browser objects.
//
// What it keeps, for offline reading only: the Check page (the app shell) and the About, Guidelines,
// Portals, Privacy and Terms pages, plus the app's own built files (/_next/static) and the icons.
// What it never keeps or answers: any /api request, any request that is not GET, any other origin,
// and the React data requests behind in-app navigation. Offer text is only ever in the browser's
// memory and in POST /api bodies, so it can never reach the cache.
//
// Pages: network first, so online visits always get a fresh page (and a fresh CSP nonce); the cached
// copy is used only when the network fails. Built files: cache first (their names change with every
// build). Each deploy serves a new worker with a new version in the cache name; when it activates,
// every older Offer Check cache is deleted.

export const CACHE_PREFIX = "offercheck-";
// The pages kept for offline reading. "/" is the Check page too.
export const OFFLINE_PAGES = ["/check", "/about", "/legal", "/portals", "/privacy", "/terms"] as const;
export const OFFLINE_ASSETS = [
  "/manifest.webmanifest",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
  "/icons/icon-maskable-512.png",
  "/icons/apple-touch-icon.png",
] as const;

// Headers for /sw.js: never cached by the browser or a CDN, so a new deploy's worker is found at
// once, and a policy of its own (the page CSP does not apply to a worker script).
export const SW_HEADERS: Record<string, string> = {
  "Content-Type": "application/javascript; charset=utf-8",
  "Cache-Control": "no-cache, no-store, must-revalidate",
  "Content-Security-Policy": "default-src 'self'; script-src 'self'",
};

// Shown for a page that is not kept offline. No script, no style, no outside resource.
const OFFLINE_HTML = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Offline · Offer Check UAE</title></head><body><h1>You are offline</h1><p>This page is not saved for offline reading. These pages are: <a href="/check">Offer Analyzer</a>, <a href="/about">About</a>, <a href="/legal">Guidelines</a>, <a href="/portals">Portals</a>, <a href="/privacy">Privacy</a>, <a href="/terms">Terms</a>. Checking an offer needs a connection.</p><div lang="ar" dir="rtl"><h2>أنت غير متصل بالإنترنت</h2><p>هذه الصفحة غير محفوظة للقراءة دون اتصال. فحص العرض يحتاج إلى اتصال.</p></div></body></html>`;

// Under `next dev`: keep nothing, delete any Offer Check cache a production build left on this
// origin, and unregister, so local code changes are never hidden by a cached page.
export const DEV_SERVICE_WORKER = `"use strict";
self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) if (key.startsWith(${JSON.stringify(CACHE_PREFIX)})) await caches.delete(key);
      await self.registration.unregister();
    })(),
  );
});
`;

export function serviceWorkerSource(version: string): string {
  if (!/^[A-Za-z0-9_.-]{1,80}$/.test(version)) throw new Error("service worker version must be a short token");
  return `// Offer Check UAE service worker. Generated by src/lib/serviceWorker.ts; see that file.
"use strict";
const CACHE = ${JSON.stringify(CACHE_PREFIX + "shell-" + version)};
const PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const PAGES = ${JSON.stringify(OFFLINE_PAGES)};
const ASSETS = ${JSON.stringify(OFFLINE_ASSETS)};
const OFFLINE_HTML = ${JSON.stringify(OFFLINE_HTML)};

function neverCached(request, url) {
  return (
    request.method !== "GET" ||
    url.origin !== self.location.origin ||
    url.pathname === "/api" ||
    url.pathname.startsWith("/api/") ||
    request.headers.has("range")
  );
}

function storable(response) {
  return Boolean(response) && response.ok && response.type === "basic" && !response.redirected;
}

function pageKey(url) {
  const path = url.pathname === "/" ? "/check" : url.pathname.replace(/\\/+$/, "");
  return PAGES.includes(path) ? path : null;
}

function isStatic(url) {
  return url.pathname.startsWith("/_next/static/") || ASSETS.includes(url.pathname);
}

function isRsc(request, url) {
  return request.headers.get("rsc") === "1" || url.searchParams.has("_rsc");
}

async function keep(cache, path) {
  try {
    const response = await fetch(path, { credentials: "same-origin", cache: "no-store" });
    if (storable(response)) await cache.put(new URL(path, self.location.origin).pathname, response);
  } catch (error) {
    // Offline during install: this file is fetched again on the next visit.
  }
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      const files = new Set(ASSETS);
      for (const page of PAGES) {
        try {
          const response = await fetch(page, { credentials: "same-origin", cache: "no-store" });
          if (!storable(response)) continue;
          const html = await response.clone().text();
          await cache.put(page, response);
          for (const match of html.matchAll(/\\/_next\\/static\\/[^"'\\s)\\\\<>]+/g)) files.add(match[0]);
        } catch (error) {
          // Offline during install: the page is kept on its next visit instead.
        }
      }
      await Promise.all([...files].map((path) => keep(cache, path)));
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        if (key.startsWith(PREFIX) && key !== CACHE) await caches.delete(key);
      }
      await self.clients.claim();
    })(),
  );
});

async function page(request, url) {
  const key = pageKey(url);
  try {
    const response = await fetch(request);
    if (key && storable(response)) {
      const cache = await caches.open(CACHE);
      await cache.put(key, response.clone());
    }
    return response;
  } catch (error) {
    const cache = await caches.open(CACHE);
    const cached = key ? await cache.match(key) : undefined;
    return (
      cached ||
      new Response(OFFLINE_HTML, {
        status: 503,
        headers: { "Content-Type": "text/html; charset=utf-8", "Content-Security-Policy": "default-src 'none'" },
      })
    );
  }
}

async function builtFile(request, url) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(url.pathname);
  if (cached) return cached;
  const response = await fetch(request);
  if (storable(response)) await cache.put(url.pathname, response.clone());
  return response;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (neverCached(request, url)) return;
  if (request.mode === "navigate") {
    event.respondWith(page(request, url));
    return;
  }
  if (isRsc(request, url)) return;
  if (isStatic(url)) event.respondWith(builtFile(request, url));
});
`;
}
